<?php
session_start();
require_once __DIR__ . '/../../../config/dbconnect.php';
require_once __DIR__ . '/../../../config/auth_guard.php';
require_once __DIR__ . '/../../../config/reportQuery.php';
require_once __DIR__ . '/../../../config/apiSecurity.php';
require_once __DIR__ . '/../../../includes/reportDocument.php';
require_once __DIR__ . '/../../../includes/reportExport.php';
requireJsonRole([1]);
requireActiveAccount($conn, true);
enforceRequestSizeLimit(2 * 1024 * 1024); // 2MB

$userId   = currentUserId();
$userName = currentUserName();

try {
    $filters = reportFiltersFromRequest($_GET);
} catch (Throwable $e) {
    reportSendErrorResponse($e, reportWantsJson(), '../reports.php');
}

if (session_status() === PHP_SESSION_ACTIVE) {
    session_write_close();
}

try {
    $report = buildReportQuery($conn, $userId, $filters);
} catch (Throwable $e) {
    reportSendErrorResponse($e, reportWantsJson(), '../reports.php');
}

$rows = $report['rows'];
if (empty($rows)) {
    reportSendNoDataResponse(reportWantsJson(), '../reports.php');
}

$filterSummary = [];
foreach ($report['filters'] as $label => $value) {
    $filterSummary[] = $label . ': ' . $value;
}

reportAuditSafely(
    $conn,
    'Export CSV Report',
    'Exported ' . $report['title'] . ' to CSV (' . $report['row_count'] . ' rows)'
);

$filename = reportDownloadFilename($report['title'], 'csv', (string) ($report['league']['league_name'] ?? ''));
reportSendDownloadHeaders($filename, 'text/csv; charset=UTF-8');

$output = fopen('php://output', 'w');
if ($output === false) {
    exit;
}

// UTF-8 BOM so Excel opens accented names correctly.
fwrite($output, "\xEF\xBB\xBF");

fputcsv($output, [$report['title']]);
$meta = ['Generated', $report['generated_at']];
if ($userName !== '') {
    $meta[] = 'Generated by';
    $meta[] = $userName;
}
$meta[] = 'Filters';
$meta[] = $filterSummary ? implode(' | ', $filterSummary) : 'None applied';
fputcsv($output, $meta);
fputcsv($output, []);

$headers = array_keys($rows[0]);
fputcsv($output, array_map(static fn(string $header): string => reportDocumentColumnLabel($header), $headers));

foreach ($rows as $row) {
    $line = [];
    foreach ($headers as $header) {
        $line[] = reportCsvValue($row[$header] ?? '');
    }
    fputcsv($output, $line);
}

fclose($output);
exit;
