<?php
session_start();
require_once __DIR__ . '/../../../vendor/autoload.php';
require_once __DIR__ . '/../../../config/dbconnect.php';
require_once __DIR__ . '/../../../config/auth_guard.php';
require_once __DIR__ . '/../../../config/reportQuery.php';
require_once __DIR__ . '/../../../config/apiSecurity.php';
require_once __DIR__ . '/../../../includes/reportDocument.php';
require_once __DIR__ . '/../../../includes/reportExport.php';
requireJsonRole([1]);
requireActiveAccount($conn, true);
enforceRequestSizeLimit(2 * 1024 * 1024); // 2MB

use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Cell\Coordinate;
use PhpOffice\PhpSpreadsheet\Cell\DataType;

$userId   = currentUserId();
$userName = currentUserName();

try {
    $filters = reportFiltersFromRequest($_GET);
} catch (Throwable $e) {
    reportSendErrorResponse($e, reportWantsJson(), '../reports.php');
}

if (session_status() === PHP_SESSION_ACTIVE) {
    session_write_close();
}

try {
    $report = buildReportQuery($conn, $userId, $filters);
} catch (Throwable $e) {
    reportSendErrorResponse($e, reportWantsJson(), '../reports.php');
}

$rows  = $report['rows'];
$title = $report['title'];

if (empty($rows)) {
    reportSendNoDataResponse(reportWantsJson(), '../reports.php');
}

try {
    $spreadsheet = new Spreadsheet();
    $sheet = $spreadsheet->getActiveSheet();
    $sheet->setTitle(substr($title, 0, 31)); // Excel limit

    $headers       = array_keys($rows[0]);
    $lastColLetter = Coordinate::stringFromColumnIndex(count($headers));

    // Title row
    $sheet->setCellValue('A1', $title);
    $sheet->getStyle('A1')->getFont()->setBold(true)->setSize(14);
    $sheet->getStyle('A1')->getFont()->getColor()->setARGB('FF09173C');
    $sheet->mergeCells('A1:' . $lastColLetter . '1');

    // Metadata row
    $meta = 'Generated: ' . $report['generated_at'];
    if ($userName !== '') {
        $meta .= ' | Generated by: ' . $userName;
    }
    foreach ($report['filters'] as $label => $value) {
        $meta .= ' | ' . $label . ': ' . $value;
    }
    $sheet->setCellValue('A2', $meta);
    $sheet->getStyle('A2')->getFont()->setItalic(true)->setSize(9)->getColor()->setARGB('FF6B7280');
    $sheet->mergeCells('A2:' . $lastColLetter . '2');

    // Header row
    $colIndex = 1;
    foreach ($headers as $header) {
        $sheet->getCell([$colIndex, 4])->setValue(reportDocumentColumnLabel($header));
        $colIndex++;
    }

    $headerRange = 'A4:' . $lastColLetter . '4';
    $sheet->getStyle($headerRange)->applyFromArray([
        'font'      => ['bold' => true, 'color' => ['argb' => 'FFFFFFFF']],
        'fill'      => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FF09173C']],
        'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER],
        'borders'   => ['bottom' => ['borderStyle' => Border::BORDER_THIN]],
    ]);

    // Data rows. User-supplied text is written explicitly as a string so a
    // team/player name beginning with "=" can never become a formula.
    $rowIndex = 5;
    foreach ($rows as $row) {
        $colIndex = 1;
        foreach ($row as $value) {
            $cell = $sheet->getCell([$colIndex, $rowIndex]);
            if (reportSpreadsheetCellType($value) === 'numeric') {
                $isFloat = is_float($value) || (is_string($value) && strpos($value, '.') !== false);
                $cell->setValueExplicit($isFloat ? (float) $value : (int) $value, DataType::TYPE_NUMERIC);
            } else {
                $cell->setValueExplicit(
                    reportStripControlChars((string) ($value ?? '')),
                    DataType::TYPE_STRING
                );
            }
            $colIndex++;
        }
        $rowIndex++;
    }

    // Column widths: auto-size is expensive on large exports.
    for ($c = 1; $c <= count($headers); $c++) {
        $letter = Coordinate::stringFromColumnIndex($c);
        if (count($rows) <= 2000) {
            $sheet->getColumnDimension($letter)->setAutoSize(true);
        } else {
            $label = reportDocumentColumnLabel((string) $headers[$c - 1]);
            $sheet->getColumnDimension($letter)->setWidth(min(40, max(12, strlen($label) + 2)));
        }
    }

    $sheet->freezePane('A5');
    $sheet->setAutoFilter('A4:' . $lastColLetter . (4 + count($rows)));

    reportAuditSafely(
        $conn,
        'Export Excel Report',
        'Exported ' . $title . ' to XLSX (' . count($rows) . ' rows)'
    );

    $filename = reportDownloadFilename($title, 'xlsx', (string) ($report['league']['league_name'] ?? ''));
} catch (Throwable $e) {
    error_log('[REPORT] Excel export failed: ' . get_class($e) . ': ' . $e->getMessage());
    reportSendErrorResponse(
        new ReportExecutionException('Unable to build the Excel export.'),
        reportWantsJson(),
        '../reports.php'
    );
}

reportSendDownloadHeaders(
    $filename,
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
);

$writer = new Xlsx($spreadsheet);
$writer->save('php://output');
exit;
